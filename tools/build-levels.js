// Builds levels.js: 60 hand-off levels per difficulty, sorted easiest-first by technique score.
// Deterministic (seeded), so re-running gives the same packs. Usage: node tools/build-levels.js
const fs = require('fs'), path = require('path');
const S = require('../sudoku.js');
const PER = 60;
const out = {};
S.DIFFICULTIES.forEach((d, k) => {
  const rand = S.makeRng(2026 + k * 1000);
  const seen = new Set(); const list = [];
  while (list.length < PER) {
    const g = S.generate(d, { rand, attempts: 1 });
    if (!g) continue;
    const key = S.toString(g.puzzle);
    if (seen.has(key)) continue;
    seen.add(key);
    list.push({ p: key, s: g.grade.score });
  }
  list.sort((a, b) => a.s - b.s);
  out[d] = list.map((x) => x.p);
  console.log(d, 'score range', list[0].s, '-', list[list.length - 1].s);
});
const js = '// Generated by tools/build-levels.js. Puzzles are 81 chars, 0 = empty.\nself.LEVELS = ' +
  JSON.stringify(out, null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'levels.js'), js);
console.log('wrote levels.js', (js.length / 1024).toFixed(1), 'KB');
